"""Integration fixtures: a dedicated DSN and disposable PostgreSQL schemas."""

import os
from uuid import uuid4

import psycopg
import pytest
from psycopg import sql

from app_final import create_app


@pytest.fixture(scope="session")
def postgres_url():
    # Never fall back to the application DSN: tests must opt into a test database.
    value = os.getenv("LAITYS_TEST_DATABASE_URL")
    if not value:
        pytest.fail("Set LAITYS_TEST_DATABASE_URL to a dedicated PostgreSQL test database")
    try:
        with psycopg.connect(value, connect_timeout=5) as connection:
            connection.execute("SELECT 1")
    except psycopg.Error:
        pytest.fail("The PostgreSQL test database is unavailable", pytrace=False)
    return value


@pytest.fixture
def schema_factory(postgres_url):
    names = []

    def allocate():
        name = "test_" + uuid4().hex
        names.append(name)
        return name

    yield allocate

    with psycopg.connect(postgres_url, autocommit=True) as connection:
        for name in names:
            # Only schemas generated by this fixture can be removed.
            assert name.startswith("test_") and len(name) == 37
            connection.execute(sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(sql.Identifier(name)))


